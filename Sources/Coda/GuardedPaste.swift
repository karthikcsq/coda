import AppKit
import os

/// A transaction owns only its own changeCount. A newer user copy always wins.
/// Inspired by Handy's MIT paste_tx/macos.rs; see THIRD_PARTY_NOTICES.md.
@MainActor final class GuardedPaste: NSObject, @preconcurrency NSPasteboardItemDataProvider {
    private let board: NSPasteboard
    private var saved: [[NSPasteboard.PasteboardType: Data]] = []
    private var ownedCount: Int?
    private struct Payload: Sendable { var text = ""; var readAt: Date? }
    private nonisolated let payload = OSAllocatedUnfairLock(initialState: Payload())
    var readAt: Date? { payload.withLock { $0.readAt } }
    var ownsClipboard: Bool { ownedCount.map { board.changeCount == $0 } ?? false }
    init(board: NSPasteboard) { self.board = board }
    func publish(_ text: String) -> Bool {
        let before = board.changeCount
        var snapshot: [[NSPasteboard.PasteboardType: Data]] = []
        for item in board.pasteboardItems ?? [] {
            var values: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                // Refuse to overwrite content that cannot be restored in full.
                guard let data = item.data(forType: type) else { return false }
                values[type] = data
            }
            snapshot.append(values)
        }
        guard board.changeCount == before else { return false }
        saved = snapshot; payload.withLock { $0.text = text; $0.readAt = nil }
        let item = NSPasteboardItem()
        item.setDataProvider(self, forTypes: [.string])
        for marker in ["org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType"] {
            item.setData(Data(), forType: .init(marker))
        }
        board.clearContents()
        let success = board.writeObjects([item])
        ownedCount = board.changeCount
        if !success { restore() }
        return success
    }
    func pasteboard(_ pasteboard: NSPasteboard?, item: NSPasteboardItem, provideDataForType type: NSPasteboard.PasteboardType) {
        guard type == .string else { return }
        let text = payload.withLock { state in
            // Further reads must not keep extending the post-consumption grace period.
            if state.readAt == nil { state.readAt = .now }
            return state.text
        }
        item.setString(text, forType: .string)
    }
    func restore() {
        defer { saved = []; ownedCount = nil; payload.withLock { $0.text = "" } }
        guard let ownedCount, board.changeCount == ownedCount else { return }
        let items = saved.map { values in
            let item = NSPasteboardItem()
            for (type, data) in values { item.setData(data, forType: type) }
            return item
        }
        board.clearContents()
        if !items.isEmpty { board.writeObjects(items) }
    }
}
